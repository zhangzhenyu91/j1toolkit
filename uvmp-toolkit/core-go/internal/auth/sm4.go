var sm4FK = [4]uint32{0xA3B1BAC6, 0x56AA3350, 0x677D9197, 0xB27022DC}

func sm4Tau(a uint32) uint32 {
	return uint32(sm4SBox[(a>>24)&0xFF])<<24 |
		uint32(sm4SBox[(a>>16)&0xFF])<<16 |
		uint32(sm4SBox[(a>>8)&0xFF])<<8 |
		uint32(sm4SBox[a&0xFF])
}

func sm4L1(b uint32) uint32 {
	return b ^ rotl(b, 2) ^ rotl(b, 10) ^ rotl(b, 18) ^ rotl(b, 24)
}

func sm4L2(b uint32) uint32 {
	return b ^ rotl(b, 13) ^ rotl(b, 23)
}

// sm4RoundKeys 生成 32 轮密钥；decrypt 时逆序（vehicle_export._sm4_round_keys）。
func sm4RoundKeys(key []byte, decrypt bool) []uint32 {
	x := [4]uint32{}
	for i := 0; i < 4; i++ {
		x[i] = uint32(key[4*i])<<24 | uint32(key[4*i+1])<<16 | uint32(key[4*i+2])<<8 | uint32(key[4*i+3])
		x[i] ^= sm4FK[i]
	}
	rk := make([]uint32, 32)
	for r := 0; r < 32; r += 4 {
		x[0] ^= sm4L2(sm4Tau(x[1] ^ x[2] ^ x[3] ^ sm4CK[r]))
		rk[r] = x[0]
		x[1] ^= sm4L2(sm4Tau(x[2] ^ x[3] ^ x[0] ^ sm4CK[r+1]))
		rk[r+1] = x[1]
		x[2] ^= sm4L2(sm4Tau(x[3] ^ x[0] ^ x[1] ^ sm4CK[r+2]))
		rk[r+2] = x[2]
		x[3] ^= sm4L2(sm4Tau(x[0] ^ x[1] ^ x[2] ^ sm4CK[r+3]))
		rk[r+3] = x[3]
	}
	if decrypt {
		for i, j := 0, 31; i < j; i, j = i+1, j-1 {
			rk[i], rk[j] = rk[j], rk[i]
		}
	}
	return rk
}

// sm4Block 单块加/解密（vehicle_export._sm4_block，rk 顺序决定方向）。
func sm4Block(block []byte, rk []uint32) []byte {
	x := [4]uint32{}
	for i := 0; i < 4; i++ {
		x[i] = uint32(block[4*i])<<24 | uint32(block[4*i+1])<<16 | uint32(block[4*i+2])<<8 | uint32(block[4*i+3])
	}
	for r := 0; r < 32; r += 4 {
		x[0] ^= sm4L1(sm4Tau(x[1] ^ x[2] ^ x[3] ^ rk[r]))
		x[1] ^= sm4L1(sm4Tau(x[2] ^ x[3] ^ x[0] ^ rk[r+1]))
		x[2] ^= sm4L1(sm4Tau(x[3] ^ x[0] ^ x[1] ^ rk[r+2]))
		x[3] ^= sm4L1(sm4Tau(x[0] ^ x[1] ^ x[2] ^ rk[r+3]))
	}
	out := make([]byte, 16)
	for j := 0; j < 16; j += 4 {
		w := x[3-j/4]
		out[j] = byte(w >> 24)
		out[j+1] = byte(w >> 16)
		out[j+2] = byte(w >> 8)
		out[j+3] = byte(w)
	}
	return out
}

// Sm4CBCDecryptHex SM4-CBC 解密 hex 密文并去 PKCS7 填充
// （vehicle_export.sm4_cbc_decrypt_hex，对应前端 sm4_decrypt(p, K, {mode:'cbc', iv:V})）。
func Sm4CBCDecryptHex(cipherHex string, key, iv []byte) ([]byte, error) {
	data, err := hex.DecodeString(cipherHex)
	if err != nil {
		return nil, fmt.Errorf("SM4 密文 hex 非法: %w", err)
	}
	if len(key) != 16 || len(iv) != 16 {
		return nil, fmt.Errorf("SM4 key/iv 必须为 16 字节")
	}
	if len(data) == 0 || len(data)%16 != 0 {
		return nil, fmt.Errorf("SM4 密文长度非法: %d", len(data))
	}
	rk := sm4RoundKeys(key, true)
	out := make([]byte, 0, len(data))
	last := iv
	for off := 0; off < len(data); off += 16 {
		block := data[off : off+16]
		dec := sm4Block(block, rk)
		plain := make([]byte, 16)
		for i := 0; i < 16; i++ {
			plain[i] = dec[i] ^ last[i]
		}
		out = append(out, plain...)
		last = block
	}
	pad := int(out[len(out)-1])
	if pad >= 1 && pad <= 16 {
		out = out[:len(out)-pad]
	}
	return out, nil
}
